/* Information Hub — article detail page. Reads ?file=data-set/<key>-<slug>.json */
"use strict";

async function init() {
  const file = queryParam("file");
  if (!file) return showError("Missing ?file parameter — open an article from the library.");
  try {
    const rec = await fetchJSON(`${DATA_DIR}/${file}`);
    render(rec);
  } catch (e) {
    showError(`Could not load article: ${e.message}`);
  }
}

function showError(msg) {
  document.getElementById("loading").classList.add("hidden");
  const err = document.getElementById("error");
  err.classList.remove("hidden");
  err.textContent = msg;
}

function render(r) {
  document.getElementById("loading").classList.add("hidden");
  const article = document.getElementById("article");
  article.classList.remove("hidden");
  document.title = `${r.title} — Information Hub`;

  // badges — use the shared badge system (collection/type/region colors)
  const badges = document.getElementById("badges");
  const col = r.collection || r.topic || "";
  const badge = (text, cls) => `<span class="badge ${cls}">${esc(text)}</span>`;
  const colCls = { "world-news": "collection-w", "tech-news": "collection-t", politics: "collection-p", products: "collection-pr", world: "collection-w", "ai-ml": "collection-t" }[col] || "collection-default";
  const colName = { "world-news": "🌍 World News", "tech-news": "🤖 Tech & AI", politics: "🏛️ Politics", products: "📦 Products", world: "🌍 World", "ai-ml": "🤖 AI/ML" }[col] || pretty(col);
  badges.innerHTML = [
    `<span class="badge ${colCls}">${esc(colName)}</span>`,
    badge(r.content_type || "", "type"),
    badge(pretty(r.region || ""), "region"),
    ...(r.tags || []).slice(0, 5).map((t) => badge(t, "type")),
  ].join("");

  document.getElementById("title").textContent = r.title;
  const src = r.source || {};
  document.getElementById("meta").innerHTML =
    `${esc(formatDate(r.date))} · ${esc(pretty(col))} · ${r.word_count ? r.word_count.toLocaleString() + " words" : ""}` +
    (src.name ? ` · <a class="text-indigo-300 hover:underline" href="${esc(src.url || "#")}" target="_blank" rel="noopener">Source: ${esc(src.name)}</a>` : "");

  // TLDR
  document.getElementById("tldr").innerHTML =
    `<div class="text-xs font-semibold text-indigo-300 uppercase tracking-wide mb-1">Summary</div>${esc(r.tldr || "")}`;

  // body
  const body = document.getElementById("body");
  const parts = [];
  if (r.background) parts.push(`<h3>Background</h3><p>${esc(r.background)}</p>`);
  (r.analysis || []).forEach((a) => {
    parts.push(`<h3>${esc(a.heading)}</h3><p>${esc(a.content)}</p>`);
  });
  if (r.key_facts && r.key_facts.length) {
    parts.push(`<h3>Key facts</h3><ul>${r.key_facts.map((f) => `<li>${esc(f)}</li>`).join("")}</ul>`);
  }
  if (r.implications && r.implications.length) {
    parts.push(`<h3>Implications</h3><ul>${r.implications.map((i) => `<li>${esc(i)}</li>`).join("")}</ul>`);
  }
  if (r.outlook) parts.push(`<h3>Outlook</h3><p>${esc(r.outlook)}</p>`);
  body.innerHTML = parts.join("");

  // entities → link to graph search on library
  const ents = document.getElementById("entities");
  ents.innerHTML = (r.entities || []).map((e) =>
    `<button class="chip" onclick="location='./library.html?q=${encodeURIComponent(e.name)}'">${esc(e.name)} <span class="opacity-50">· ${esc(e.type)}</span></button>`
  ).join("") || `<span class="text-sm text-slate-400">None recorded.</span>`;

  // related items — cross-link via index (needs id→file map)
  const relIds = (r.related_items || []).map((x) => x.split("/").pop()).filter(Boolean);
  renderRelated(relIds, r.related_notes || []);

  // provenance + grounding + review
  const prov = document.getElementById("provenance");
  const g = r.grounding || {};
  const rev = r.review || {};
  const gen = (r.provenance || {}).generated_by || {};
  // checked_by / approved_by are OBJECTS ({provider, model}) in the schema
  const byName = (o) => (o && typeof o === "object" ? (o.provider || o.model || "AI") : o || "—");
  const method = g.method || "";
  const methodLabel = method === "gemini" ? "🤖 AI check (Gemini)"
    : method === "lexical" ? "⚙️ Lexical check" : "pending";
  const verified = g.checked_by
    ? `${methodLabel}${g.grounding_score != null ? " · score " + g.grounding_score : ""}${(g.claims_grounded != null && g.claims_total) ? " · " + g.claims_grounded + "/" + g.claims_total + " claims" : ""}`
    : "pending";
  prov.innerHTML = [
    `<div><b>Generated by:</b> ${esc(gen.provider || "—")} / ${esc(gen.model || "—")}${gen.prompt_version ? " · prompt " + esc(String(gen.prompt_version).replace(/^v/i, "v")) : ""}</div>`,
    `<div><b>Verified:</b> ${esc(verified)}</div>`,
    `<div><b>Review:</b> ${esc(rev.status || "pending")}${rev.approved_by ? " · " + esc(byName(rev.approved_by)) : ""}</div>`,
    `<div><b>ID:</b> ${esc(r.id || "")}</div>`,
  ].join("");
}

async function renderRelated(relIds, notes) {
  const wrap = document.getElementById("related");
  wrap.innerHTML = `<div class="text-sm text-slate-400">Loading related…</div>`;
  try {
    const index = await fetchJSON(`${DATA_DIR}/views/index.json`);
    const byId = {};
    index.forEach((it) => { byId[it.id] = it; });
    const shown = new Set();
    const items = [];
    // prefer resolved notes (filenames), fall back to ids
    relIds.forEach((id) => {
      const it = byId[id];
      if (it && !shown.has(it.id)) { shown.add(it.id); items.push(it); }
    });
    if (items.length === 0) {
      wrap.innerHTML = `<span class="text-sm text-slate-400">No related briefings yet.</span>`;
      return;
    }
    wrap.innerHTML = items.map((it) => `
      <a href="${articleHref(it)}" class="mini-card block px-4 py-3">
        <div class="text-xs text-slate-500">${esc(formatDate(it.date))} · ${esc(pretty(it.collection || it.topic || ""))}</div>
        <div class="font-medium text-slate-100">${esc(it.title)}</div>
      </a>`).join("");
  } catch (e) {
    wrap.innerHTML = `<span class="text-sm text-slate-400">Related unavailable.</span>`;
  }
}

function pretty(name) {
  return String(name || "").replace(/[-_]/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}

document.addEventListener("DOMContentLoaded", init);
